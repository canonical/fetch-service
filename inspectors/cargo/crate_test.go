var libc_url = "https://static.crates.io:443/crates/libc/0.2.155/download"

// Part of the contents of Cargo.toml for the libc crate
var libc_cargotoml = `# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO
[package]
name = "libc"
version = "0.2.155"
authors = ["The Rust Project Developers", "Another Author"]
build = "build.rs"
exclude = [
    "/ci/*",
    "/.github/*",
    "/.cirrus.yml",
    "/triagebot.toml",
]
autobins = false
autoexamples = false
autotests = false
autobenches = false
description = """
Raw FFI bindings to platform libraries like libc.
"""
license = "MIT OR Apache-2.0"
`

func (s *cargoSuite) TestCargoInspectorID(c *C) {
	ins := cargo.NewCrateInspector()
	c.Assert(ins.ID(), Equals, "cargo.crate")
}

func (s *cargoSuite) TestCargoInspectRequest(c *C) {
	ins := cargo.NewCrateInspector()
	a := metadata.NewArtifact()
	a.CurrentDownload = metadata.Download{URL: libc_url}

	err := ins.InspectRequest(a)
	c.Assert(err, IsNil)

	insp, ok := a.RequestInspection[ins.ID()]
	c.Assert(ok, Equals, true)
	c.Assert(insp.Opinion, Equals, opinions.Unknown)
	c.Assert(insp.Reason, Equals, "unsupported origin")

	c.Assert(a.RequestInspection[ins.ID()].Annotations["package-name"], Equals, "libc")
	c.Assert(a.RequestInspection[ins.ID()].Annotations["package-version"], Equals, "0.2.155")
}

