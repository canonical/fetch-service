func (s *cargoSuite) TestCargoInspectArtifact(c *C) {
	tmp := c.MkDir()
	filename := filepath.Join(tmp, "libc-0.2.155.crate")

	err := createTarball(filename, "libc-0.2.155", libc_cargotoml)
	if err != nil {
		panic(err)
	}

	ins := cargo.NewCrateInspector()
	a := createArtifact(ins)

	f, err := files.OpenArtifactFile(filename)
	c.Assert(err, IsNil)
	defer f.Close()

	err = ins.InspectArtifact(f, a)
	c.Assert(err, IsNil)
	c.Assert(a.Approved(), Equals, true)

	c.Check(a.Metadata.Type, Equals, "application/x.rust.crate")
	c.Check(a.Metadata.Name, Equals, "libc")
	c.Check(a.Metadata.Version, Equals, "0.2.155")
	c.Check(a.Metadata.Vendor, Equals, "")
	c.Check(a.Metadata.Description, Equals, "Raw FFI bindings to platform libraries like libc.")
	c.Check(a.Metadata.Author, Equals, "The Rust Project Developers, Another Author")
	c.Check(a.Metadata.AuthorEmail, Equals, "")
	c.Check(a.Metadata.License, Equals, "MIT OR Apache-2.0")
	c.Assert(a.Approved(), Equals, true)
}

