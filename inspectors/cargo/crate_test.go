func createTarball(filename, subdir, contents string) error {
	archive, err := os.Create(filename)
	if err != nil {
		panic(err)
	}
	defer archive.Close()

	zip_writer := gzip.NewWriter(archive)
	defer zip_writer.Close()
	tar_writer := tar.NewWriter(zip_writer)
	defer tar_writer.Close()

	// Create a tarball with a "Cargo.toml" file inside the libc-0.2.155/ dir
	header := &tar.Header{
		Name: fmt.Sprintf("%s/Cargo.toml", subdir),
		Size: int64(len(contents)),
	}

	err = tar_writer.WriteHeader(header)
	if err != nil {
		return err
	}

	_, err = tar_writer.Write([]byte(contents))
	if err != nil {
		return err
	}

	return nil
}

func createArtifact(ins Inspector) *metadata.Artifact {
	h, _ := digests.NewSha1Digest("42962163ae017f7c2ffbcb79e4268e9c6250b8d9") //nolint: errcheck

	a := metadata.NewArtifact()
	a.Metadata.Type = "application/gzip"
	a.Metadata.Sha1 = h
	a.MimeType = mimetype.Lookup("application/gzip")
	a.CurrentDownload.URL = libc_url
	a.RequestInspection[ins.ID()] = &Inspection{
		Opinion:     opinions.Pending,
		Reason:      "some reason",
		Annotations: Annotation{"package-name": "libc", "package-version": "0.2.155"},
	}

	return a
}
